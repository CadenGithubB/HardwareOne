#!/usr/bin/env python3
"""Pin the Android interoperability fixtures in tools/ble_secure/fixtures by SHA-256.

The app copies these files into its test resources and pins the same hashes,
so a fixture never changes silently:
  - the v1 files (inner protocol v1, frozen: production no longer speaks it, so
    they can never be regenerated) and X3 (phone_pipe_v1_passphrase.json, still
    generated by test_phone_passphrase.py and unchanged by phone link v2);
  - the phone link v2 files, generated and compared byte for byte by
    test_phone_secure_channel.py (needs the pinned crypto build). After a
    deliberate --write-vectors run, update V2_PINS here and in the app.
No compiler or ESP-IDF is needed. --sanitize is accepted and ignored (CTest
passes it to every phone suite).
"""
import argparse
import hashlib
import json
from pathlib import Path

FIXTURES = Path(__file__).resolve().parents[4] / 'tools/ble_secure/fixtures'
V1_PINS = {
    'phone_pipe_v1_sessions.json': '19ce9539fdd676eefa3ad624625a6772a399c6e3662efe7c7bdf8585bfc758c9',
    'phone_pipe_v1_negative.json': '7b2722a4e6d1590785615068ea529eb661fa49d23b2eed5893a0a063f7588460',
    'phone_pipe_v1_passphrase.json': 'b076c2e2bb9a367e306370d2b0375ae4060dd503ab22f8c527b56f088e8d7d4c',
    'phone_secure_channel_v1_vectors.json': '0a53fe8c0a63a2d9f283aa52310e1ec787cfe42d15c9b8a61573d47172513b38',
    'secure_channel_v1_vectors.json': '2ffd40a47dcc3bc1095a6eb8dd6628cc5e6276c0946bee02f07f76fd735ca3d3',
}
V2_PINS = {
    'phone_secure_channel_v1_pipe_v2_vectors.json': '82ebdb2ee13cea29febfbed7c10453b178393d097c638b207180c5b2ff7be44b',
    'phone_pipe_v2_sessions.json': 'a29d385260b7619736044813620ea15c438b5f7605c5495667712e1eaa6aac73',
    'phone_pipe_v2_negative.json': '04d4b25e46734bfc83cf004f6c03079a8175072a3c6bc2db46ab004ddb965660',
    'phone_console_v2_records.json': '781868582f5e876795d6d20fac35d1682cf84c17f3e35048aa2a7b3694a65f2e',
}


def sha256(name):
    return hashlib.sha256((FIXTURES / name).read_bytes()).hexdigest()


def check_pins(pins):
    wrong = {name: sha256(name) for name, pin in pins.items() if sha256(name) != pin}
    assert not wrong, f'fixture SHA-256 differs from its pin: {wrong}'


def check_v1_pins():
    check_pins(V1_PINS)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sanitize', action='store_true')
    parser.parse_args()
    check_v1_pins()
    check_pins(V2_PINS)
    for name in V2_PINS:
        # The generator writes indent=2 JSON with a final newline; a hand edit
        # or reformat shows here even before the hash is looked at.
        text = (FIXTURES / name).read_text()
        assert text == json.dumps(json.loads(text), indent=2) + '\n', f'{name} is not in generator form'
    print(f'Phone fixtures: {len(V1_PINS)} frozen v1 files (X3 included) and {len(V2_PINS)} v2 files match '
          'their SHA-256 pins')
