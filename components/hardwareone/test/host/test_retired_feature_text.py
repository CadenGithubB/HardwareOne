#!/usr/bin/env python3
"""Retired features are neither advertised nor kept as dead settings.

Camera timed auto-capture (cameraautocapture, cameraautocaptureinterval,
camerasendaftercapture, cameratargetdevice), the automatic battery-level power
mode and the Edge Impulse input-size setting (eiinputsize) were removed or
report "not available". This suite reads the real sources and checks that:

- the camera, power and edgeimpulse module descriptions in
  System_CommandRegistry.cpp name only commands that the module's own
  CommandEntry table registers, name none of the retired commands, and the
  power description does not promise an automatic low-battery switch;
- no CommandEntry table registers a retired command;
- System_Settings.h no longer declares or defaults edgeImpulseInputSize and
  no production source under components/hardwareone reads it;
- docs/COMMAND_REFERENCE.md (generated by tools/command_registry.py) lists no
  retired command and carries the current camera, power and edgeimpulse
  descriptions, i.e. it was regenerated after they changed.

Not covered: the commands' runtime replies (power auto is covered by
test_power_cpu_frequency.py, the Edge Impulse geometry by
test_edge_impulse_jpeg.py) and docs/USERGUIDE.md, which is hand-written.

--cxx and --sanitize are accepted for CTest uniformity; nothing is compiled.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys

HERE = Path(__file__).resolve().parent
COMPONENT = HERE.parents[1]
REPO = HERE.parents[3]
sys.path.insert(0, str(REPO))

from tools import command_registry  # noqa: E402

RETIRED_COMMANDS = (
    "cameraautocapture",
    "cameraautocaptureinterval",
    "camerasendaftercapture",
    "cameratargetdevice",
    "eiinputsize",
)
# module -> word pattern for the module's own command names in its description
MODULE_TOKENS = {
    "camera": r"\bcamera[a-z0-9]+\b",
    "power": r"\bpower[a-z]+\b",
    "edgeimpulse": r"\bei[a-z]+\b",
}


class Report:
    def __init__(self) -> None:
        self.failures = 0
        self.total = 0

    def check(self, name: str, ok: bool, detail: str = "") -> None:
        self.total += 1
        if ok:
            print(f"PASS {name}")
        else:
            self.failures += 1
            print(f"FAIL {name}" + (f"   [{detail}]" if detail else ""))


def reference_section(text: str, module: str) -> str:
    m = re.search(rf"^## {re.escape(module)}\n(.*?)(?=^## |\Z)", text, re.M | re.S)
    return m.group(1) if m else ""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cxx", default=None)
    parser.add_argument("--sanitize", action="store_true")
    parser.parse_args()

    report = Report()
    modules = {m["module"]: m for m in command_registry.parse_modules()}
    commands = command_registry.parse_commands()
    every_name = {c["name"] for rows in commands.values() for c in rows}

    for module, pattern in MODULE_TOKENS.items():
        mod = modules.get(module)
        report.check(f"{module}: module is registered", mod is not None)
        if mod is None:
            continue
        blurb = mod["summary"]
        own = {c["name"] for c in commands.get(mod["array"], [])}
        named = set(re.findall(pattern, blurb))
        unknown = sorted(named - own)
        report.check(f"{module}: description names only registered commands",
                     not unknown, ", ".join(unknown))
        retired = sorted(n for n in RETIRED_COMMANDS if re.search(rf"\b{n}\b", blurb))
        report.check(f"{module}: description names no retired command",
                     not retired, ", ".join(retired))

    camera = modules.get("camera", {}).get("summary", "")
    report.check("camera: description does not promise timed capture or ESP-NOW delivery",
                 not re.search(r"drive timed capture|delivery to a named peer", camera),
                 camera[-200:])
    power = modules.get("power", {}).get("summary", "")
    report.check("power: description does not promise an automatic low-battery switch",
                 not re.search(r"power auto <on\|off> enables|automatic low-battery downshift"
                               r"|auto-mode state", power),
                 power[:400])

    registered = sorted(n for n in RETIRED_COMMANDS if n in every_name)
    report.check("no CommandEntry table registers a retired command",
                 not registered, ", ".join(registered))

    settings_h = (COMPONENT / "System_Settings.h").read_text(encoding="utf-8", errors="replace")
    report.check("System_Settings.h has no edgeImpulseInputSize field or default",
                 "edgeImpulseInputSize" not in settings_h)
    readers = sorted(p.name for p in command_registry.sources()
                     if "edgeImpulseInputSize" in p.read_text(encoding="utf-8", errors="replace"))
    report.check("no production source reads edgeImpulseInputSize", not readers,
                 ", ".join(readers))

    reference_path = REPO / "docs" / "COMMAND_REFERENCE.md"
    reference = reference_path.read_text(encoding="utf-8") if reference_path.exists() else ""
    report.check("docs/COMMAND_REFERENCE.md exists", bool(reference), str(reference_path))
    listed = sorted(n for n in RETIRED_COMMANDS if f"| `{n}` |" in reference)
    report.check("command reference lists no retired command", not listed, ", ".join(listed))
    for module in MODULE_TOKENS:
        blurb = modules.get(module, {}).get("summary", "").strip()
        section = reference_section(reference, module)
        report.check(f"command reference carries the current {module} description "
                     "(regenerate with python3 tools/command_registry.py reference)",
                     bool(blurb) and f"> {blurb}\n" in section)

    print(f"{report.total - report.failures}/{report.total} retired-feature checks passed")
    return 1 if report.failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
