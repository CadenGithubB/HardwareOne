INSTANCE_ONE = {
    "encoderAutoStart": "encoderautostart",
    "encoderBrightness": "ledbrightness encoder",
    "encoderAddress": "encoderaddress",
    "encoderBus": "encoderbus",
}
FIELDS = {  # field -> (cmdKey of instance n, without the number; type; label start)
    "AutoStart": ("encoderautostart {n}", "bool", "Open after boot"),
    "Brightness": ("ledbrightness encoder{n}", "int", "Brightness (%)"),
    "Address": ("encoderaddress {n}", "int", "I2C address (next open)"),
    "Bus": ("encoderbus {n}", "int", "I2C bus (reboot required)"),
}


def check_schema(schema: dict, names: set[str]) -> list[str]:
    failures = []
    modules = schema.get("modules", [])
    if len(modules) != 1 or modules[0].get("section") != "hardware.encoder":
        return [f"expected the one encoder module, got {modules}"]
    entries = modules[0]["entries"]
    by_key = {entry["key"]: entry for entry in entries}
    if len(by_key) != len(entries):
        failures.append("two rows share a jsonKey")
    commands = [entry.get("cmdKey") for entry in entries]
    if len(set(commands)) != len(commands):
        failures.append("two rows share a cmdKey")
    for entry in entries:
        command = entry.get("cmdKey")
        if not command:
            failures.append(f"{entry['key']}: no cmdKey in the schema (its setter does not bind)")
            continue
        if not FORM.fullmatch(command):
            failures.append(f"{entry['key']}: cmdKey \"{command}\" does not have the name form")
        if command not in names and command.split()[0] not in names:
            failures.append(f"{entry['key']}: cmdKey \"{command}\" binds to no registered command")
    for key, command in INSTANCE_ONE.items():
        entry = by_key.get(key)
        if not entry or entry.get("cmdKey") != command:
            failures.append(f"instance 1's {key} changed: {entry}")
    instances = len(entries) // len(FIELDS)
    if instances != 4 or len(entries) != instances * len(FIELDS):
        failures.append(f"expected 4 instances x {len(FIELDS)} rows, got {len(entries)} rows")
    for n in range(2, instances + 1):
        for field, (command, kind, label) in FIELDS.items():
            key = f"encoder{n}{field}"
            entry = by_key.get(key)
            if not entry:
                failures.append(f"missing row {key}")
                continue
            if entry.get("cmdKey") != command.format(n=n) or entry.get("type") != kind:
                failures.append(f"{key}: cmdKey/type {entry.get('cmdKey')}/{entry.get('type')}")
            if entry.get("label") != f"Encoder {n}: {label}":
                failures.append(f"{key}: label \"{entry.get('label')}\" does not name instance {n}")
        address = by_key.get(f"encoder{n}Address", {})
        if (address.get("default") != 0 or address.get("min") != 0 or address.get("max") != 0x50
                or not str(address.get("options", "")).startswith("0|not set,")):
            failures.append(f"encoder{n}Address: not an unset-by-default address row: {address}")
    first = by_key.get("encoderAddress", {})
    if first.get("default") != 0x49 or first.get("min") != 0x36 or "not set" in first.get("options", ""):
        failures.append(f"instance 1's address row changed: {first}")
    return failures


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--cxx", default=os.environ.get("CXX") or shutil.which("c++"))
    parser.add_argument("--sanitize", action="store_true")
    args = parser.parse_args()
    require(bool(args.cxx), "a host C++17 compiler is required")

    encoder = (COMPONENT / "i2csensor_encoder.cpp").read_text()
    settings = (COMPONENT / "System_Settings.cpp").read_text()
    settings_header = (COMPONENT / "System_Settings.h").read_text()
    editor = (COMPONENT / "System_SettingsEditorCore.cpp").read_text()

    _, commands, _ = measure(COMPONENT)
    names = {name for name, _, _, _ in commands}
    require({"encoderaddress", "encoderautostart", "encoderbus", "ledbrightness"} <= names,
            "the encoder's setter commands are not registered in the sources")

    def definition(opening: str) -> str:
        at = settings_header.index(opening)
        return extract_block(settings_header[at:], opening[:-1].rstrip()) + ";"
    types = "\n".join(definition(opening) for opening in (
        "enum SettingType {", "struct SettingEntry {", "struct SettingsModule {"))
    table = extract_block(encoder, "constexpr SettingEntry settings[]") + ";"
    require("ENCODER_INSTANCE_ROWS(2)" in table, "the encoder table no longer generates instance 2's rows")
    production = "\n\n".join([
        extract_block(editor, "const char* settingsEditorCommandName(const SettingEntry* entry)"),
        extract_block(editor, "bool settingsEditorHasCommand(const SettingEntry* entry)"),
        extract_block(settings, "static JsonObject jsonPathCreate("),
        extract_block(settings, "static JsonVariantConst jsonPathRead("),
        extract_block(settings, "void applyRegisteredDefaults()"),
        extract_block(settings, "static int settingsLoadClampInt("),
        re.search(r"^static uint32_t gSettingsTypeMismatches[^\n]+", settings, re.M)[0],
        extract_block(settings, "enum SettingLoadVerdict") + ";",
        extract_block(settings, "static SettingLoadVerdict settingsTypeCheck("),
        extract_block(settings, "static float settingsLoadClampFloat("),
        extract_block(settings, "size_t readRegisteredSettings("),
        extract_block(settings, "size_t writeRegisteredSettings("),
        extract_block(settings, "void buildSettingsSchemaJson(JsonDocument& doc)"),
    ])
    unit = HARNESS
    for marker, content in (("COMMANDS", ",\n".join(json.dumps(name) for name in sorted(names))),
                            ("TYPES", types), ("TABLE", table), ("PRODUCTION", production)):
        require(unit.count("// INSERT_" + marker + "\n") == 1, f"expected one insertion point: {marker}")
        unit = unit.replace("// INSERT_" + marker + "\n", content + "\n")

    with tempfile.TemporaryDirectory(prefix="hw1-encoder-instance-settings-") as directory:
        tmp = Path(directory)
        (tmp / "Arduino.h").write_text((HERE / "web_batch_stubs/Arduino.h").read_text())
        (tmp / "test.cpp").write_text(unit)
        command = [args.cxx, "-std=c++17", "-Wall", "-Wextra", "-Werror", "-pedantic",
                   "-Wno-unused-function", "-Wno-unused-variable", "-Wno-sign-compare",
                   "-Wno-missing-field-initializers",
                   "-I", str(tmp), "-I", str(COMPONENT), "-I", str(JSON_INCLUDE),
                   str(tmp / "test.cpp"), "-o", str(tmp / "test")]
        if args.sanitize:
            command[1:1] = ["-fsanitize=address,undefined", "-fno-omit-frame-pointer", "-g"]
        subprocess.run(command, check=True, timeout=120)
        result = subprocess.run([str(tmp / "test")], check=True, timeout=60, capture_output=True, text=True)
    failures = check_schema(json.loads(result.stdout.strip().splitlines()[-1]), names)
    for failure in failures:
        print(f"FAIL {failure}", file=sys.stderr)
    if failures:
        raise SystemExit("encoder_instance_settings: FAILED")
    print("Encoder instance settings passed (defaults, save/load round trip of 4 instances, schema rows "
          "with bound cmdKeys of the name form)")


if __name__ == "__main__":
    main()
