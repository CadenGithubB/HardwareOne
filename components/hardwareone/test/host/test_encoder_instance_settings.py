#!/usr/bin/env python3
"""The encoder's settings rows of every instance (multi-instance phase 1c).

Instance 1 keeps its four rows (encoderAutoStart, encoderBrightness,
encoderAddress, encoderBus) and their commands; instances 2..4 get flat,
numbered rows generated by ENCODER_INSTANCE_ROWS (i2csensor_encoder_light.h):
encoder2Address with cmdKey "encoderaddress 2", and so on. The audit tools
read only string-literal rows, so the generated ones are checked here, on the
production table compiled from i2csensor_encoder.cpp:

- defaults: instance 1 as before (address 0x49, bus 0, brightness 50, off),
  instances 2..4 unset (address 0), bus 0, brightness 50, off;
- a save and a load round-trip every instance's values under
  hardware.encoder.encoder<N><Field>, instance 1 under its old keys;
- the settings schema (buildSettingsSchemaJson with the editor core's command
  predicate) lists every row with its cmdKey, so the generic editors offer
  them: every cmdKey binds by its first word to a command registered in the
  sources (the rule of tools/command_registry.py audit) and has the name
  form [a-z0-9]+( [a-z0-9]+)* (test_command_name_form.py);
- jsonKeys and cmdKeys are unique, and instance n's labels name it.

Compiled: the real table, jsonPathCreate/Read, the load type gate and clamps,
readRegisteredSettings, writeRegisteredSettings, applyRegisteredDefaults,
buildSettingsSchemaJson and settingsEditorCommandName/HasCommand, with the
real vendored ArduinoJson.
"""
